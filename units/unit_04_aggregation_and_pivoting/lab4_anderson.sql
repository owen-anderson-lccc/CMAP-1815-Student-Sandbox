-- ----------------------------------------------------------------------------
-- CHALLENGE 5: The Executive Regional Matrix (Session 2)
-- Scenario: The VP of Sales needs a quarterly revenue matrix from superstore.
-- Task:
-- 1. Group by region (handle NULL regions with COALESCE(region, 'Unknown')).
-- 2. Calculate total_orders (COUNT(*)) and total_sales (SUM(sales)).
-- 3. Pivot category sales into separate columns using CASE inside SUM:
--    - furniture_sales (sales where category = 'Furniture')
--    - office_sales (sales where category = 'Office Supplies')
--    - tech_sales (sales where category = 'Technology')
-- 4. Add tech_pct: The percentage of total sales generated by Technology.
-- 5. Order by total_sales descending.
-- ----------------------------------------------------------------------------

-- Write your solution below:

SELECT 
    COALESCE(l.state, 'Unknown') AS region,
    COUNT(o.order_id) AS total_orders,
    SUM(ol.quantity * ol.unit_price) AS total_sales,
    SUM(CASE WHEN p.category = 'Furniture' THEN (ol.quantity * ol.unit_price) ELSE 0 END) AS furniture_sales,
SUM(CASE WHEN p.category = 'Office Supplies' THEN (ol.quantity * ol.unit_price) ELSE 0 END) AS office_sales,
SUM(CASE WHEN p.category = 'Technology' THEN (ol.quantity * ol.unit_price) ELSE 0 END) AS tech_sales,
    ROUND(
        SUM(CASE WHEN p.category = 'Technology' THEN (ol.quantity * ol.unit_price) ELSE 0 END * 100.0) / NULLIF(SUM(ol.quantity * ol.unit_price), 0), 
        2
    ) AS tech_pct
FROM 
    orders o
JOIN 
    employees e ON o.employee_id = e.employee_id -- Connects order to the employee who made it
JOIN 
    locations l ON e.location_id = l.location_id -- Connects employee to their location/state
JOIN 
    order_lines ol ON o.order_id = ol.order_id
JOIN 
    products p ON ol.product_id = p.product_id
GROUP BY 
    COALESCE(l.state, 'Unknown')
ORDER BY 
    total_sales DESC;